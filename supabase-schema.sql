revoke all on portfolio_experiences from anon, authenticated;
revoke all on portfolio_projects from anon, authenticated;
revoke all on portfolio_skills from anon, authenticated;

grant select on portfolio_profile to anon, authenticated;
grant select on portfolio_about to anon, authenticated;
grant select on portfolio_highlights to anon, authenticated;
grant select on portfolio_experiences to anon, authenticated;
grant select on portfolio_projects to anon, authenticated;
grant select on portfolio_skills to anon, authenticated;

alter table portfolio_profile enable row level security;
alter table portfolio_about enable row level security;
alter table portfolio_highlights enable row level security;
alter table portfolio_experiences enable row level security;
alter table portfolio_projects enable row level security;
alter table portfolio_skills enable row level security;

