create table if not exists portfolio_profile (
  id smallint primary key default 1 check (id = 1),
  first_name text not null,
  last_name text not null,
  headline text not null,
  positioning text not null,
  favorite_stack text not null,
  location text not null,
  photo_url text default '',
  email text not null,
  phone_link text not null,
  phone_display text not null,
  github_url text not null,
  github_label text not null,
  legacy_portfolio_url text not null,
  contact_note text not null
);

create table if not exists portfolio_about (
  id smallint primary key default 1 check (id = 1),
  title text not null,
  paragraphs text[] not null default '{}'
);

create table if not exists portfolio_highlights (
  id bigint generated by default as identity primary key,
  text text not null,
  display_order int not null default 0
);

create table if not exists portfolio_experiences (
  id bigint generated by default as identity primary key,
  period text not null,
  title text not null,
  description text not null,
  display_order int not null default 0
);

create table if not exists portfolio_projects (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  stack text not null default '',
  image text not null default '',
  url text not null,
  link_label text not null,
  display_order int not null default 0
);

create table if not exists portfolio_skills (
  id bigint generated by default as identity primary key,
  label text not null,
  description text not null,
  display_order int not null default 0
);

revoke all on portfolio_profile from anon, authenticated;
